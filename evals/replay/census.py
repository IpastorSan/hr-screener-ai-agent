"""The state census: which states the engine really reaches in the replay corpus.

A state is classed by its `stage` plus the hidden flags that change what the next turn does
(`FLAGS`); every distinct `ConversationState` in the corpus, given or returned, counts once.
"""

import json
from collections import Counter
from collections.abc import Callable, Iterable, Iterator, Mapping
from pathlib import Path
from typing import Any

from evals.replay.corpus import Case, is_state
from sazon.engine.models import Stage
from sazon.engine.spec import QUALIFIED_STEP, agent
from sazon.engine.state import ConversationState
from sazon.engine.upgrade import downgrade, is_v1

CENSUS_PATH = Path(__file__).parents[2] / "docs" / "engine" / "state-census.md"

type State = Mapping[str, Any]

FLAGS: dict[str, Callable[[State], bool | str | None]] = {
    "not_consented": lambda s: s["stage"] != Stage.CONSENT and not s["consented"],
    "outcome": lambda s: s["outcome"],
    "booking": lambda s: s["booking"] is not None,
    "offered_slots": lambda s: bool(s["offered_slots"]),
    "pending_question": lambda s: s["pending_question"] is not None,
    "pending_identity": lambda s: s["pending_identity"] is not None,
    "pending_clarification": lambda s: s["pending_clarification"] is not None,
    "pending_confirmation": lambda s: s["pending_confirmation"] is not None,
    "first_name_only": lambda s: s["first_name_only"] is not None,
    "fix_field": lambda s: s["fix_field"] is not None,
    "contact_notice": lambda s: s["contact_notice"] is not None,
    "pause_offered": lambda s: s["pause_offered"],
    "de_escalated": lambda s: s["de_escalated"],
    "paused": lambda s: s["paused"],
    "slot_which_asked": lambda s: s["slot_which_asked"],
    "slots_declined": lambda s: s["slots_declined"],
    "cancel_offered": lambda s: s["cancel_offered"],
    "amending": lambda s: s["amending"] is not None,
    "move_to": lambda s: s["move_to"] is not None,
    "reopenable": lambda s: s["reopenable"],
    "opted_out": lambda s: s["opted_out"],
    "restarted": lambda s: s["restarted"],
    "duplicate_of": lambda s: s["duplicate_of"] is not None,
}
"""The flags of the census key. `outcome` shows its value; the others whether they are set."""

FUNNEL = [step for step in agent().funnel.steps if step != QUALIFIED_STEP]
STAGE_ORDER = {
    step: index for index, step in enumerate((*FUNNEL, Stage.MODE, Stage.SCHEDULING, Stage.DONE))
}
"""The funnel's order, then the interview's and the end."""
DEFAULTS: dict[str, Any] = downgrade(ConversationState().model_dump(mode="json"))


def flat(state: State) -> State:
    """A state as version 1 stored it (`engine/upgrade.py`): the census counts the flags'
    pairs, whichever shape the corpus was recorded in."""
    return state if is_v1(state) else downgrade(state)


def states(cases: Iterable[Case]) -> Iterator[tuple[str, State]]:
    """Every state in the corpus, given or returned, flat, with the journey it came from."""
    for case in cases:
        out = case["out"]
        for value in [*case["args"].values(), *(out if isinstance(out, list) else [out])]:
            if is_state(value):
                yield case["case"], flat(value)


def key(state: State) -> tuple[str, tuple[str, ...]]:
    flags: list[str] = []
    for name, read in FLAGS.items():
        value = read(state)
        if isinstance(value, str):
            flags.append(f"{name}={value}")
        elif value:
            flags.append(name)
    return state["stage"], tuple(flags)


def _canonical(state: State) -> str:
    return json.dumps(state, sort_keys=True)


def render(cases: Iterable[Case]) -> str:
    counts: Counter[tuple[str, tuple[str, ...]]] = Counter()
    examples: dict[tuple[str, tuple[str, ...]], str] = {}
    set_in: Counter[str] = Counter()
    seen: set[str] = set()
    for journey, state in states(cases):
        canonical = _canonical(state)
        if canonical in seen:
            continue
        seen.add(canonical)
        combination = key(state)
        counts[combination] += 1
        examples.setdefault(combination, journey)
        for field, default in DEFAULTS.items():
            if state.get(field, default) != default:
                set_in[field] += 1

    ordered = sorted(counts, key=lambda k: (STAGE_ORDER[k[0]], -counts[k], k[1]))
    stages = {stage for stage, _ in counts}
    reached_flags = {flag.split("=")[0] for _, flags in counts for flag in flags}
    lines = [
        "# Engine state census",
        "",
        "Generated by `make replay` (`evals/replay/census.py`) from the replay corpus "
        "(`evals/replay/corpus.jsonl.gz`): every distinct `ConversationState` given to or "
        "returned by the engine while the journeys and the e2e personas run offline.",
        "",
        "A combination is the `stage` plus the hidden flags set in the state: `outcome` with its "
        "value, the others when not at their default (`not_consented`: past the consent stage "
        "without consent). The example is the first journey (`group.id`) or persona "
        "(`e2e.id`) that reached it; `+derived` marks calls made on a recorded state that no "
        "journey makes (nudges, idle close, calendar cancellation; `record.derived`), `+synth.*` "
        "scripted extractions the offline extractor cannot produce (`evals/replay/synth.py`).",
        "",
        "This is the version 1 view of the state, a `stage` plus flags, which the corpus "
        "records and the version 1 reader (`backend/src/sazon/engine/upgrade.py`) is tested "
        "against. The engine now keeps one `phase` instead (`backend/src/sazon/engine/state.py`); "
        "a state stored in that shape is written back as flags before it is counted.",
        "",
        "The states as the engine declares them, with every transition between them, are in "
        "the statechart [states.mmd](states.mmd) (`make diagram`); "
        "`evals/replay/tests/test_transitions.py` checks the corpus takes those and only those.",
        "",
        f"{len(seen)} distinct states in {len(counts)} combinations, "
        f"{len(stages)} of {len(STAGE_ORDER)} stages.",
        "",
        "| Stage | Flags | States | Example |",
        "|---|---|---|---|",
    ]
    for combination in ordered:
        stage, flags = combination
        shown = ", ".join(f"`{flag}`" for flag in flags) or "-"
        lines.append(f"| {stage} | {shown} | {counts[combination]} | {examples[combination]} |")

    never_stages = [stage for stage in STAGE_ORDER if stage not in stages]
    never_flags = [name for name in FLAGS if name not in reached_flags]
    never_fields = [field for field in DEFAULTS if not set_in[field]]
    lines += [
        "",
        "## Never reached",
        "",
        f"- Stages: {', '.join(f'`{s}`' for s in never_stages) or 'none'}.",
        f"- Census flags: {', '.join(f'`{f}`' for f in never_flags) or 'none'}.",
        "- `ConversationState` fields never off their default in any recorded state: "
        + (", ".join(f"`{f}`" for f in never_fields) or "none")
        + ".",
        "",
        "## Fields off their default",
        "",
        "Distinct states in which each `ConversationState` field differs from its default.",
        "",
        "| Field | States |",
        "|---|---|",
    ]
    lines += [f"| `{field}` | {set_in[field]} |" for field in DEFAULTS]
    return "\n".join(lines) + "\n"


def write(cases: Iterable[Case], path: Path = CENSUS_PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(cases), encoding="utf-8")
